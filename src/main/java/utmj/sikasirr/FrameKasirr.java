    private void hitungTotal() {
        try {
            int harga = Integer.parseInt(txtHarga.getText());
            int jumlah = Integer.parseInt(txtJumlah.getText());
            String namaBarang = txtNama.getText();
            
            if (harga <= 0 || jumlah <= 0) {
                JOptionPane.showMessageDialog(this, 
                        "Harga dan jumlah harus lebih dari 0!", 
                        "Peringatan", 
                        JOptionPane.WARNING_MESSAGE);
                return;
            }
            if (namaBarang.trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, 
                        "Kolom Nama Barang ini wajib diisi ya mas!", 
                        "Peringatan", 
                        JOptionPane.WARNING_MESSAGE);
                return;
            } 
            int total = (harga * jumlah);
            txtTotal.setText(String.valueOf(total));
            
        } catch(NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, 
                    "Harga dan jumlah harus berupa angka ya!", 
                    "Peringatan", 
                    JOptionPane.WARNING_MESSAGE);
        }
    }

    
    private void Bayar() {  
        try {
            if (txtBayar.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, 
                        "Kolom Uang Bayar ini juga wajib diisi dong neng!", 
                        "Peringatan", 
                        JOptionPane.WARNING_MESSAGE);
                txtBayar.requestFocus();
                return;
            }
            
            int bayar = Integer.parseInt(txtBayar.getText());
            int harga = Integer.parseInt(txtHarga.getText());
            int jumlah = Integer.parseInt(txtJumlah.getText());
            int total = harga * jumlah;
            
            // Validasi Pembayaran
            if (bayar < total) {
                JOptionPane.showMessageDialog(this, 
                        "Uang Pembayaran Kurang!\nTotal belanja: Rp " + total + 
                        "\nUang dibayar: Rp " + bayar + 
                        "\nKekurangan Rp " + (total - bayar), 
                        "Pembayaran Gagal", 
                        JOptionPane.WARNING_MESSAGE);
            return;
            }
            
            // Menghitung Kembalian
            int kembali = bayar - total;
            txtKembali.setText(Integer.toString(kembali));
            
            JOptionPane.showMessageDialog(this, 
                    "Pembayaran berhasil!\nKembalian: Rp " + kembali, 
                    "Pembayaran berhasil", 
                    JOptionPane.INFORMATION_MESSAGE);
                    
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, 
                    "Masukkan angka yang valid ya!", "Peringatan", 
                    JOptionPane.WARNING_MESSAGE);
        } 
    }
